static float make_advance(unsigned code){
    for(unsigned i=0;i<ARRAY_COUNT(make_glyphs);++i)
        if(make_glyphs[i].code==code)return (float)make_glyphs[i].advance*0.022f;
    if(code>=0x300 && code<=0x36f)return 0;
    return 22; /* Conservative full-em fallback for localized/modded glyphs. */
}
static void trim_make_name(const wchar_t *name,wchar_t out[256]){
    unsigned n=0;float width=0;
    while(n<255 && name[n]){width+=make_advance(name[n]);++n;}
    if(width<=222){memory_copy(out,name,n*sizeof(wchar_t));out[n]=0;return;}
    float available=222-3*make_advance('.');unsigned end=0; width=0;
    while(end<n){
        unsigned units=1;float advance=make_advance(name[end]);
        if(name[end]>=0xd800 && name[end]<=0xdbff && end+1<n && name[end+1]>=0xdc00 && name[end+1]<=0xdfff){units=2;advance=22;}
        if(end+units>252 || width+advance>available)break;
        width+=advance;end+=units;
    }
    while(end && name[end-1]==' ')--end;
    memory_copy(out,name,end*sizeof(wchar_t));
    out[end++]='.';out[end++]='.';out[end++]='.';out[end]=0;
}

