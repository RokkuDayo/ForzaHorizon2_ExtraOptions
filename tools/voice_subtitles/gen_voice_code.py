#!/usr/bin/env python3
"""Generate features/voice_subtitles_code.h: the assembled hook code of voice_hooks.py, embedded into the Extra Options DLL.
Needs the keystone Python module (pip install keystone-engine). Run after changing voice_hooks.py, then rebuild
with build.py.

The blob is linked for LINK_CAVE but placed at run time wherever free memory near the game image is found, so it
carries a relocation table, derived here by assembling at several cave addresses and diffing:
  vc_rel_abs64  8-byte absolute pointers into the cave (vtable slots, object vtables): add (cave - LINK_CAVE);
  vc_rel_rel32  4-byte displacements to game code (call SetText, jmp back): subtract (cave - LINK_CAVE).
rip-relative references inside the blob need no fixup. The table is verified by relocating to another address and
comparing with a direct assembly there."""
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import voice_hooks as H  # noqa: E402

BASE = H.IMAGE_BASE
LINK_CAVE = BASE + 0x3A20000
# Odd deltas so the lowest byte of every address-dependent field differs (the field starts at the first changed byte).
PROBE_DELTAS = (0x1111, -0x2345671, 0x13579BD)
VERIFY_CAVE = BASE - 0x10000000


def relocations(link_cave):
    blob, offs = H.build(link_cave, BASE)
    probes = []
    for d in PROBE_DELTAS:
        other, other_offs = H.build(link_cave + d, BASE)
        assert other_offs == offs and len(other) == len(blob)
        probes.append((d, other))
    abs64, rel32 = [], []
    i = 0
    while i < len(blob):
        if all(o[i] == blob[i] for _, o in probes):
            i += 1
            continue
        a64 = struct.unpack_from("<Q", blob, i)[0] if i + 8 <= len(blob) else None
        a32 = struct.unpack_from("<i", blob, i)[0] if i + 4 <= len(blob) else None
        if a64 is not None and all(struct.unpack_from("<Q", o, i)[0] - a64 == d for d, o in probes):
            abs64.append(i)
            i += 8
        elif a32 is not None and all(struct.unpack_from("<i", o, i)[0] - a32 == -d for d, o in probes):
            rel32.append(i)
            i += 4
        else:
            raise SystemExit(f"address-dependent bytes at +0x{i:X} are neither abs64 nor rel32")
    return blob, offs, abs64, rel32


def relocate(blob, abs64, rel32, delta):
    out = bytearray(blob)
    for i in abs64:
        struct.pack_into("<Q", out, i, (struct.unpack_from("<Q", out, i)[0] + delta) & 0xFFFFFFFFFFFFFFFF)
    for i in rel32:
        struct.pack_into("<i", out, i, struct.unpack_from("<i", out, i)[0] - delta)
    return bytes(out)


blob, offs, abs64, rel32 = relocations(LINK_CAVE)
assert relocate(blob, abs64, rel32, VERIFY_CAVE - LINK_CAVE) == H.build(VERIFY_CAVE, BASE)[0], "relocation check failed"
code_off = offs["pool"] + H.POOL_SIZE
code = blob[code_off:].rstrip(b"\0")
head = blob[:offs["ring"]]
for i in abs64 + rel32:  # every fixup lies in the copied parts of the blob
    assert i + 4 <= len(head) or code_off <= i < code_off + len(code), hex(i)


def arr(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def offsets(name, values):
    rows = [", ".join(f"0x{v:X}" for v in values[i:i + 8]) for i in range(0, len(values), 8)]
    return f"static const unsigned {name}[{len(values)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


out = ["/* generated by tools/voice_subtitles/gen_voice_code.py from voice_hooks.py - do not edit */",
       f"#define VC_LINK_CAVE 0x{LINK_CAVE:X}ULL /* the blob is assembled for this address; relocate by vc_rel_* */",
       f"#define VC_CAVE_SIZE 0x{H.CAVE_SIZE:X}",
       f"#define VC_OFF_COUNT 0x{offs['table_count']:X}",
       f"#define VC_OFF_TABLE 0x{offs['table']:X}",
       f"#define VC_OFF_POOL 0x{offs['pool']:X}",
       f"#define VC_OFF_CODE 0x{code_off:X}",
       f"#define VC_TABLE_MAX {H.TABLE_MAX}",
       f"#define VC_POOL_SIZE 0x{H.POOL_SIZE:X}",
       f"#define VC_N_HOOKS {len(H.HOOKS)}",
       f"#define VC_N_REL_ABS64 {len(abs64)}",
       f"#define VC_N_REL_REL32 {len(rel32)}",
       arr("vc_head", head), arr("vc_code", code),
       "/* Blob offsets of absolute pointers into the cave (+ delta) and of rel32 displacements to game code (- delta). */",
       offsets("vc_rel_abs64", abs64), offsets("vc_rel_rel32", rel32),
       "/* site: game address; hook: blob offset of its entry point. */",
       "static const struct { unsigned long long site; unsigned hook, ndisp; unsigned char orig[8]; } vc_hooks[VC_N_HOOKS] = {"]
for key, (va, nd, orig) in H.HOOKS.items():
    out.append(f"  {{0x{va:X}ULL, 0x{offs['hook_' + key]:X}, {nd}, {{" + ", ".join(f"0x{b:02x}" for b in orig.ljust(8, b"\0")) + "}},")
out.append("};\n")
dst = HERE.parents[1] / "features" / "voice_subtitles_code.h"
dst.write_text("\n".join(out), encoding="utf-8", newline="\r\n")  # CRLF, like the other sources
print(f"{dst}: head {len(head)} B, code {len(code)} B at +0x{code_off:X}, relocs abs64 {len(abs64)} rel32 {len(rel32)}")
